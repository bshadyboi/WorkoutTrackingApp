const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = ts.transpileModule(fs.readFileSync('src/lib/overload.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const sandbox = { exports: {} }; vm.runInNewContext(source, sandbox);
const suggest = sandbox.exports.suggestNTTarget;
const p = (reps, rir, weight = 180) => ({ weight, reps, rir });
const run = (previous, rest = {}) => suggest({ previous, previousSets: [previous,previous], expectedSets: 2, repRange: '2×8–12', targetRir: 1, increment: 5, ...rest });
assert.equal(run(p(10,2)).reps,11);
assert.equal(run(p(10,1)).kind,'hold');
assert.equal(run(p(10,0)).kind,'hold');
assert.equal(run(p(12,null)).kind,'hold');
assert.equal(run(p(12,1),{ previousSets:[p(12,1),p(10,2)] }).kind,'hold');
assert.equal(run(p(12,1),{ previousSets:[p(12,1)] }).kind,'hold');
assert.equal(run(p(12,1),{ previousSets:[p(12,1),p(12,1,170)] }).kind,'hold');
assert.equal(run(p(12,1),{ increment:0 }).kind,'hold');
assert.equal(run(p(12,1),{ noLoadIncrease:true }).kind,'hold');
assert.equal(run(p(12,1)).weight,185);
assert.equal(run(p(12,1)).reps,8);
assert.equal(run(p(8,4)).kind,'add-reps');
assert.equal(run(p(12,2,0)).kind,'hold');
assert.equal(run(undefined,{previousSets:[]}).kind,'open');
assert.equal(run(p(7,2)).kind,'hold');
assert.equal(run(p(12,NaN)).kind,'hold');
assert.equal(run(p(12,1),{repRange:'25 min'}),null);
console.log('17 NT target checks passed: reps, RIR, full-set readiness, equipment increments, missing/invalid history, and load limits.');
